const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { PGlite } = require('@electric-sql/pglite');

test('Porquinho no PostgreSQL: isolamento, saldo protegido, idempotência e exclusão', async () => {
  const db = new PGlite();
  const a = '11111111-1111-4111-8111-111111111111', b = '22222222-2222-4222-8222-222222222222';
  const login = async (id, role = 'authenticated') => { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]); await db.exec(`set role ${role}`); };
  const mover = async (id, tipo, valor, pedido) => (await db.query('select (public.movimentar_cofrinho($1,$2,$3,$4)).saldo as saldo', [id,tipo,valor,pedido])).rows[0].saldo;
  const pedido = (n) => `33333333-3333-4333-8333-${String(n).padStart(12,'0')}`;
  try {
    await db.exec(`create role anon nologin; create role authenticated nologin; create role service_role nologin bypassrls;
      create schema auth; create table auth.users(id uuid primary key,email text,raw_user_meta_data jsonb default '{}');
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      grant usage on schema auth,public to anon,authenticated,service_role; grant execute on function auth.uid() to anon,authenticated,service_role;`);
    for (const file of ['schema.sql','migrations/202611120001_hardening.sql','migrations/202611120002_free_ai.sql','migrations/202611240001_quotes_quota.sql','migrations/202611240002_piggy_bank.sql']) await db.exec(fs.readFileSync(path.join(__dirname,'../../supabase',file),'utf8'));
    await db.query('insert into auth.users(id,email) values ($1,$2),($3,$4)', [a,'a@example.com',b,'b@example.com']);
    await login(a);
    const idA = (await db.query("insert into public.cofrinhos(nome,meta) values ('Reserva A',1000) returning id")).rows[0].id;
    await login(b);
    const idB = (await db.query("insert into public.cofrinhos(nome,meta) values ('Viagem B',2000) returning id")).rows[0].id;
    assert.equal((await db.query('select * from public.cofrinhos where id=$1',[idA])).rows.length,0);
    await assert.rejects(mover(idA,'guardar',500,pedido(1)), /não encontrado/i);
    await assert.rejects(db.query('insert into public.cofrinhos(usuario_id,nome,meta) values ($1,$2,10)',[a,'Invasão']), /row-level security/i);
    assert.equal((await db.query("update public.cofrinhos set nome='Invasão' where id=$1 returning id",[idA])).rows.length,0);
    await login(a);
    await assert.rejects(db.exec('update public.cofrinhos set saldo=999'), /permission denied/i);
    await assert.rejects(db.exec('update public.cofrinhos set usuario_id=null'), /permission denied/i);
    await assert.rejects(db.exec("insert into public.cofrinhos(nome,meta,saldo) values ('Fraude',100,100)"), /permission denied/i);
    await assert.rejects(db.exec('insert into public.movimentos_cofrinho default values'), /permission denied/i);
    assert.equal(Number(await mover(idA,'guardar',500,pedido(1))),500);
    assert.equal(Number(await mover(idA,'guardar',500,pedido(1))),500);
    assert.equal(Number(await mover(idA,'retirar',200,pedido(2))),300);
    assert.equal(Number(await mover(idA,'guardar',500,pedido(1))),300);
    await assert.rejects(mover(idA,'guardar',501,pedido(1)), /outros dados/i);
    assert.equal((await db.query('select * from public.movimentos_cofrinho')).rows.length,2);
    assert.equal((await db.query('delete from public.cofrinhos where id=$1 returning id',[idA])).rows.length,0);
    for (const valor of [0,-1,1.001,'NaN','Infinity',100000000000]) await assert.rejects(mover(idA,'guardar',valor,pedido(3)), /inválido/i);
    await assert.rejects(mover(idA,'transferir',1,pedido(3)), /inválido/i);
    await assert.rejects(mover(idA,'retirar',301,pedido(3)), /insuficiente/i);
    assert.equal(Number(await mover(idA,'retirar',250,pedido(3))),50);
    await assert.rejects(mover(idA,'retirar',250,pedido(4)), /insuficiente/i);
    await login(b);
    assert.equal((await db.query('select * from public.movimentos_cofrinho')).rows.length,0);
    assert.equal(Number(await mover(idB,'guardar',10,pedido(1))),10);
    await login('', 'anon');
    for (const sql of ['select * from public.cofrinhos','select * from public.movimentos_cofrinho',`select public.movimentar_cofrinho(${idA},'guardar',1,'${pedido(5)}')`]) await assert.rejects(db.exec(sql),/permission denied/i);
    await login(''); await assert.rejects(mover(idA,'guardar',1,pedido(5)), /Sessão inválida/i);
    await db.exec('reset role');
    await db.exec(fs.readFileSync(path.join(__dirname,'../../supabase/migrations/202611240002_piggy_bank.sql'),'utf8'));
    assert.equal((await db.query('select * from public.cofrinhos')).rows.length,2);
    await login(a); assert.equal(Number(await mover(idA,'retirar',50,pedido(5))),0);
    await db.query('delete from public.cofrinhos where id=$1',[idA]);
    assert.equal((await db.query('select * from public.movimentos_cofrinho')).rows.length,0);
    await db.exec('reset role'); await db.query('delete from auth.users where id=$1',[b]);
    assert.equal((await db.query('select * from public.cofrinhos')).rows.length,0);
    assert.equal((await db.query('select * from public.movimentos_cofrinho')).rows.length,0);
  } finally { await db.close(); }
});
